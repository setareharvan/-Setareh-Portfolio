// ---------- Initialization ----------
const htmlRoot = document.getElementById('htmlRoot');
const themeToggle = document.getElementById('themeToggle');
const langToggle = document.getElementById('langToggle');

const savedTheme = localStorage.getItem('theme') || 'dark';
const savedLang = localStorage.getItem('lang') || 'fa';

setTheme(savedTheme);
setLanguage(savedLang);

// ---------- Theme Toggle Logic ----------
function setTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
  localStorage.setItem('theme', theme);
  const icon = themeToggle.querySelector('i');
  if (theme === 'light') {
    icon.classList.remove('fa-sun');
    icon.classList.add('fa-moon');
  } else {
    icon.classList.remove('fa-moon');
    icon.classList.add('fa-sun');
  }
}

themeToggle.addEventListener('click', () => {
  const currentTheme = document.documentElement.getAttribute('data-theme');
  const newTheme = currentTheme === 'light' ? 'dark' : 'light';
  setTheme(newTheme);
});

// ---------- Language Toggle Logic ----------
function setLanguage(lang) {
  htmlRoot.setAttribute('lang', lang);
  htmlRoot.setAttribute('dir', lang === 'fa' ? 'rtl' : 'ltr');
  localStorage.setItem('lang', lang);

  langToggle.textContent = lang === 'fa' ? 'EN' : 'FA';

  // 1. Translate text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (Object.prototype.hasOwnProperty.call(translations[lang], key)) {
      el.textContent = translations[lang][key];
    }
  });

  // 2. Translate placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (Object.prototype.hasOwnProperty.call(translations[lang], key)) {
      el.setAttribute('placeholder', translations[lang][key]);
    }
  });

  // 3. Translate aria-labels for accessibility
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (Object.prototype.hasOwnProperty.call(translations[lang], key)) {
      el.setAttribute('aria-label', translations[lang][key]);
    }
  });

  // 4. Update page title
  document.title = translations[lang].page_title;
}

langToggle.addEventListener('click', () => {
  const currentLang = htmlRoot.getAttribute('lang');
  const newLang = currentLang === 'fa' ? 'en' : 'fa';
  setLanguage(newLang);
});

// ---------- Existing Features (Navbar, Scroll, Form) ----------
const navbar = document.getElementById('navbar');
window.addEventListener('scroll', () => {
  navbar.classList.toggle('scrolled', window.scrollY > 50);
});

const menuToggle = document.getElementById('menuToggle');
const navLinks = document.getElementById('navLinks');
menuToggle.addEventListener('click', () => {
  navLinks.classList.toggle('active');
  const icon = menuToggle.querySelector('i');
  icon.classList.toggle('fa-bars');
  icon.classList.toggle('fa-times');
});

navLinks.querySelectorAll('a').forEach(link => {
  link.addEventListener('click', () => {
    navLinks.classList.remove('active');
    const icon = menuToggle.querySelector('i');
    icon.classList.add('fa-bars');
    icon.classList.remove('fa-times');
  });
});

const revealElements = document.querySelectorAll('.reveal');
const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('active');
    }
  });
}, { threshold: 0.1 });
revealElements.forEach(el => revealObserver.observe(el));

// Contact Form with AJAX
const contactForm = document.getElementById('contactForm');
const submitBtn = document.getElementById('submitBtn');
const successMessage = document.getElementById('successMessage');

contactForm.addEventListener('submit', async function(e) {
  e.preventDefault();
  const formData = new FormData(this);
  const originalBtnText = submitBtn.innerHTML;
  
  submitBtn.disabled = true;
  const currentLang = htmlRoot.getAttribute('lang');
  const loadingText = currentLang === 'fa' ? '<i class="fas fa-spinner fa-spin"></i> در حال ارسال...' : '<i class="fas fa-spinner fa-spin"></i> Sending...';
  submitBtn.innerHTML = loadingText;

  try {
    const response = await fetch('https://formspree.io/f/xvkkbppo', {
      method: 'POST',
      body: formData,
      headers: { 'Accept': 'application/json' }
    });

    if (response.ok) {
      successMessage.style.display = 'block';
      contactForm.reset();
      setTimeout(() => { successMessage.style.display = 'none'; }, 5000);
    } else {
      alert(currentLang === 'fa' ? 'خطا در ارسال پیام. لطفاً دوباره تلاش کنید.' : 'Error sending message. Please try again.');
    }
  } catch (error) {
    alert(currentLang === 'fa' ? 'خطا در ارسال پیام. لطفاً دوباره تلاش کنید.' : 'Error sending message. Please try again.');
  } finally {
    submitBtn.disabled = false;
    submitBtn.innerHTML = originalBtnText;
  }
});
